MELT_RELAX_TEMPLATE = """\
# Step 1: Relax structure before melting point calculation
# Generated by lammps-input-server

units           metal
dimension       3
boundary        p p p
atom_style      atomic

read_data       {structure_file}

{potential_block}

# Relax box and atoms
fix             1 all box/relax aniso 0.0
minimize        1.0e-10 1.0e-10 10000 100000
unfix           1

# Thermal equilibration at 300 K
velocity        all create 300.0 12345 dist gaussian
fix             2 all npt temp 300.0 300.0 0.1 aniso 0.0 0.0 1.0
thermo          100
thermo_style    custom step temp pe ke etotal press vol lx ly lz
run             10000
unfix           2

write_data      relaxed.data
print "Relaxation complete. Output: relaxed.data"
"""


MELT_INTERFACE_TEMPLATE = """\
# Step 2: Create solid-liquid interface
# Generated by lammps-input-server

units           metal
dimension       3
boundary        p p p
atom_style      atomic

read_data       relaxed.data
{replicate_line}

{potential_block}

# Define upper and lower regions
variable        zmax equal zhi
variable        zmid equal (zhi+zlo)/2.0
region          upper block INF INF INF INF ${{zmid}} ${{zmax}}
group           upper region upper
group           lower subtract all upper

# Melt the upper half at high temperature
velocity        all create {melt_temp} 12345 dist gaussian
fix             1 all npt temp {melt_temp} {melt_temp} 0.1 aniso 0.0 0.0 1.0
thermo          100
thermo_style    custom step temp pe ke etotal press vol
run             20000
unfix           1

# Cool to near estimated melting point
fix             2 all npt temp {melt_temp} {equil_temp} 0.1 aniso 0.0 0.0 1.0
run             10000
unfix           2

# Equilibrate at estimated melting point
fix             3 all npt temp {equil_temp} {equil_temp} 0.1 aniso 0.0 0.0 1.0
run             20000
unfix           3

write_data      interface.data
print "Interface created. Output: interface.data"
"""


MELT_COEXIST_TEMPLATE = """\
# Step 3: Temperature ramp to find melting point via coexistence
# Generated by lammps-input-server

units           metal
dimension       3
boundary        p p p
atom_style      atomic

read_data       interface.data

{potential_block}

# NVE + Langevin thermostat for coexistence
# The system will naturally evolve toward the melting point
velocity        all create {equil_temp} 54321 dist gaussian

# Long NPH run — system finds its own melting temperature
fix             1 all nph aniso 0.0 0.0 1.0
thermo          100
thermo_style    custom step temp pe ke etotal press vol lx ly lz

# Dump trajectory for analysis
dump            1 all custom 500 melt_coexist.dump id type x y z

run             100000
unfix           1

print "Coexistence run complete."
print "Analyze temperature plateau in thermo output to determine melting point."
"""


def format_potential_block(pair_style: str, pair_coeff: str) -> str:
    """Format the pair_style + pair_coeff lines."""
    return f"pair_style      {pair_style}\npair_coeff      {pair_coeff}"
